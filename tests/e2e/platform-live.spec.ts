import { expect, test } from "@playwright/test";
test.describe("Global administration (synthetic development fixtures)",()=>{
  test.skip(!process.env.E2E_PASSWORD,"Requires synthetic development accounts");
  test("admin creates club, assigns owner, activates, suspends and archives; nonadmins cannot mutate",async({page,browser},info)=>{
    const slug=`stage4-${info.project.name}-${Date.now()}`;
    await page.goto("/login");
    await page.getByLabel("E-mail",{exact:true}).fill(process.env.E2E_ADMIN_EMAIL!);
    await page.getByLabel("Senha",{exact:true}).fill(process.env.E2E_PASSWORD!);
    await page.getByRole("button",{name:"Entrar",exact:true}).click();
    await expect(page).toHaveURL(/\/fan$/);
    await page.goto("/admin");
    await page.getByRole("link",{name:"Novo clube",exact:true}).click();
    await page.getByLabel("Nome do clube",{exact:true}).fill(`Clube sintético ${slug}`);
    await page.getByLabel("Endereço do clube (slug)",{exact:true}).fill(slug);
    await page.getByLabel("Cidade",{exact:true}).fill("São Paulo");
    await page.getByLabel("Estado",{exact:true}).selectOption("SP");
    await page.getByLabel("Motivo da alteração",{exact:true}).fill("Criação sintética automatizada de desenvolvimento");
    await page.getByRole("button",{name:"Criar clube em rascunho"}).click();
    await expect(page.getByText("Alterações salvas.",{exact:true})).toBeVisible();
    const detail=page.url().split('?')[0];const id=detail.split('/').at(-1)!;
    const clubForm=page.locator('form[action$="/salvar"]');
    await clubForm.getByLabel("Situação do clube",{exact:true}).selectOption("active");
    await clubForm.getByLabel("Motivo da alteração",{exact:true}).fill("Tentativa sintética de ativar sem responsável");
    await clubForm.getByRole("button",{name:"Salvar clube",exact:true}).click();
    await expect(page.locator("main").getByRole("alert")).toContainText("não foi permitida");
    const staffForm=page.locator('form[action$="/equipe"]').last();
    await staffForm.getByLabel("E-mail da conta",{exact:true}).fill(process.env.E2E_MANAGER_EMAIL!);
    await staffForm.getByLabel("Papel no clube",{exact:true}).selectOption("owner");
    await staffForm.getByLabel("Motivo da alteração",{exact:true}).fill("Atribuição sintética auditada do responsável");
    await staffForm.getByRole("button",{name:"Adicionar à equipe"}).click();
    await expect(page.getByText("Alterações salvas.",{exact:true})).toBeVisible();
    await clubForm.getByLabel("Situação do clube",{exact:true}).selectOption("active");
    await clubForm.getByLabel("Motivo da alteração",{exact:true}).fill("Ativação sintética com responsável cadastrado");
    await clubForm.getByRole("button",{name:"Salvar clube",exact:true}).click();
    await expect(page.getByText("Alterações salvas.",{exact:true})).toBeVisible();
    const manager=await browser.newContext({baseURL:"http://127.0.0.1:3000"});
    try {
      const mp=await manager.newPage();await mp.goto("/login");
      await mp.getByLabel("E-mail",{exact:true}).fill(process.env.E2E_MANAGER_EMAIL!);
      await mp.getByLabel("Senha",{exact:true}).fill(process.env.E2E_PASSWORD!);
      await mp.getByRole("button",{name:"Entrar",exact:true}).click();await expect(mp).toHaveURL(/\/fan$/);
      await mp.goto(`/gestao/${slug}`);await expect(mp.getByRole("heading",{name:`Gestão: Clube sintético ${slug}`})).toBeVisible();
      const denied=await manager.request.post("/admin/clubes/acoes/equipe",{headers:{Origin:"http://127.0.0.1:3000"},form:{id,email:process.env.E2E_FAN_EMAIL!,role:"owner",status:"active",reason:"Tentativa sintética não autorizada",expected_role:"",expected_status:""},maxRedirects:0});
      expect(denied.status()).toBe(303);expect(denied.headers().location).toContain("acesso-negado");
      await page.locator("summary").first().click();
      const existing=page.locator('details form');await existing.getByLabel("Situação do vínculo",{exact:true}).selectOption("revoked");
      await existing.getByLabel("Motivo da alteração",{exact:true}).fill("Teste sintético de revogação do último responsável");
      await existing.getByRole("button",{name:"Salvar vínculo"}).click();await expect(page.locator("main").getByRole("alert")).toContainText("não foi permitida");
      await clubForm.getByLabel("Situação do clube",{exact:true}).selectOption("suspended");
      await clubForm.getByLabel("Motivo da alteração",{exact:true}).fill("Suspensão sintética para verificar bloqueio de acesso");
      await clubForm.getByRole("button",{name:"Salvar clube",exact:true}).click();await expect(page.getByText("Alterações salvas.",{exact:true})).toBeVisible();
      await mp.goto(`/gestao/${slug}`);await expect(mp).toHaveURL(/acesso-negado/);
      await clubForm.getByLabel("Situação do clube",{exact:true}).selectOption("archived");
      await clubForm.getByLabel("Motivo da alteração",{exact:true}).fill("Arquivamento sintético ao concluir o teste automatizado");
      await clubForm.getByRole("button",{name:"Salvar clube",exact:true}).click();await expect(page.getByRole("button",{name:"Salvar clube",exact:true})).toBeDisabled();
      await expect(page.getByRole("button",{name:"Adicionar à equipe"})).toHaveCount(0);
    } finally {await manager.close();}
    await page.goto(`/admin?q=${encodeURIComponent(slug)}`);await expect(page.getByRole("link",{name:`Clube sintético ${slug}`,exact:true})).toBeVisible();
  });
});
